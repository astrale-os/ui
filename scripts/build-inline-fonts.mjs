import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/*
 * Writes `packages/ui/src/fonts/hanken-grotesk-inline.ts` from the latin Hanken Grotesk file the
 * astrale preset loads, so the inlined font never drifts from it. A contract test checks the
 * committed module.
 */

const fonts = new URL('../packages/ui/src/theme/fonts/', import.meta.url)
const output = new URL('../packages/ui/src/fonts/hanken-grotesk-inline.ts', import.meta.url)

export async function renderHankenGroteskFontFace() {
  const latin = await readFile(new URL('hanken-grotesk-latin-wght-normal.woff2', fonts))
  return (
    "@font-face{font-family:'Hanken Grotesk';font-style:normal;font-weight:100 900;font-display:swap;" +
    `src:url(data:font/woff2;base64,${latin.toString('base64')}) format('woff2')}`
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const module = [
    '// Generated by `pnpm fonts:build` from `../theme/fonts/hanken-grotesk-latin-wght-normal.woff2`.',
    '',
    '/**',
    " * The `@font-face` rule of Hanken Grotesk's latin subset (weights 100 to 900), the typeface of",
    ' * the astrale preset, with the font inlined as a `data:` URL. Put it in the `<style>` of a page',
    ' * that cannot load the preset; its Content-Security-Policy then needs `font-src data:`.',
    ' */',
    `export const hankenGroteskFontFace = ${JSON.stringify(await renderHankenGroteskFontFace())}`,
    '',
  ]
  await writeFile(output, module.join('\n'))
}
