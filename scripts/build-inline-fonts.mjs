import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/*
 * Writes `packages/ui/src/fonts/manrope-inline.ts` from the latin Manrope file the astrale preset
 * loads, so the inlined font never drifts from it. A contract test checks the committed module.
 */

const fonts = new URL('../packages/ui/src/theme/fonts/', import.meta.url)
const output = new URL('../packages/ui/src/fonts/manrope-inline.ts', import.meta.url)

export async function renderManropeFontFace() {
  const latin = await readFile(new URL('manrope-latin-wght-normal.woff2', fonts))
  return (
    "@font-face{font-family:'Manrope';font-style:normal;font-weight:200 800;font-display:swap;" +
    `src:url(data:font/woff2;base64,${latin.toString('base64')}) format('woff2')}`
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const module = [
    '// Generated by `pnpm fonts:build` from `../theme/fonts/manrope-latin-wght-normal.woff2`.',
    '',
    '/**',
    " * The `@font-face` rule of Manrope's latin subset (weights 200 to 800), the heading font of the",
    ' * astrale preset, with the font inlined as a `data:` URL. Put it in the `<style>` of a page that',
    ' * cannot load the preset; its Content-Security-Policy then needs `font-src data:`.',
    ' */',
    `export const manropeFontFace = ${JSON.stringify(await renderManropeFontFace())}`,
    '',
  ]
  await writeFile(output, module.join('\n'))
}
